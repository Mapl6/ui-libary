/**
 * Code generator for the UI library.
 *
 *   node scripts/generate.ts           generate once
 *   node scripts/generate.ts --watch   regenerate when components or tokens change
 *
 * Outputs (committed, never edited by hand):
 *   src/styles/tokens.css                   CSS variables + Tailwind @theme from src/tokens
 *   src/registry/generated/components.ts    every component with a `<slug>.meta.tsx`
 *   src/registry/generated/loaders.ts       lazy meta loaders for client components
 */
import { existsSync, readdirSync, readFileSync, watch, writeFileSync, mkdirSync } from "node:fs"
import path from "node:path"
import ts from "typescript"

import type { PropDoc, PropGroup, PropKind } from "../src/lib/registry/types.ts"

const root = path.resolve(import.meta.dirname, "..")
const uiDir = path.join(root, "src/components/ui")
const tokensDir = path.join(root, "src/tokens")
const generatedDir = path.join(root, "src/registry/generated")

const HEADER = "// This file is generated by scripts/generate.ts. Do not edit it by hand.\n"

/* -------------------------------------------------------------------------- */
/*  Helpers                                                                   */
/* -------------------------------------------------------------------------- */

const rel = (file: string) => path.relative(root, file).split(path.sep).join("/")

function toPascal(slug: string) {
  return slug.replace(/(^|[-_])(\w)/g, (_, __, c: string) => c.toUpperCase())
}

function toCamel(slug: string) {
  const pascal = toPascal(slug)
  return pascal.charAt(0).toLowerCase() + pascal.slice(1)
}

function titleFromFile(file: string) {
  const base = path.basename(file, path.extname(file)).replace(/^\d+[-_]/, "")
  const words = base.split(/[-_]/).join(" ")
  return words.charAt(0).toUpperCase() + words.slice(1)
}

/** Writes a file only when its content changed, so watchers and HMR stay quiet. */
function writeIfChanged(file: string, content: string) {
  mkdirSync(path.dirname(file), { recursive: true })
  if (existsSync(file) && readFileSync(file, "utf8") === content) return false
  writeFileSync(file, content)
  return true
}

/* -------------------------------------------------------------------------- */
/*  Tokens → CSS                                                              */
/* -------------------------------------------------------------------------- */

async function generateTokens() {
  // Cache-bust so --watch picks up edits to the token modules.
  const stamp = `?t=${Date.now()}`
  const load = (name: string) => import(path.join(tokensDir, name) + stamp)
  const [{ themes }, typo, { spacingUnit }, { radius }, { shadows }, { breakpoints }, { zIndex }, motion] =
    await Promise.all([
      load("themes.ts"),
      load("typography.ts"),
      load("spacing.ts"),
      load("radius.ts"),
      load("shadows.ts"),
      load("breakpoints.ts"),
      load("z-index.ts"),
      load("motion.ts"),
    ])

  type Theme = { id: string; scheme: string; colors: Record<string, string> }
  const allThemes = themes as Theme[]
  const [defaultTheme] = allThemes
  if (!defaultTheme) throw new Error("src/tokens/themes.ts must define at least one theme")

  const block = (selector: string, theme: Theme) =>
    [
      `${selector} {`,
      `  color-scheme: ${theme.scheme};`,
      ...Object.entries(theme.colors).map(([role, value]) => `  --ui-${role}: ${value};`),
      "}",
    ].join("\n")

  const entries = (prefix: string, obj: Record<string, string>) =>
    Object.entries(obj).map(([k, v]) => `  --${prefix}-${k}: ${v};`)

  const fontSizes = Object.entries(typo.fontSize as Record<string, [string, string]>).flatMap(
    ([k, [size, lh]]) => [`  --text-${k}: ${size};`, `  --text-${k}--line-height: ${lh};`]
  )

  const css = [
    "/* This file is generated by scripts/generate.ts from src/tokens. Do not edit it by hand. */",
    "",
    block(":root", defaultTheme),
    "",
    ...allThemes.map((t) => block(`[data-theme="${t.id}"]`, t) + "\n"),
    "@theme inline {",
    // Only design-system colors exist: no ad-hoc palette utilities like `bg-blue-500`.
    "  --color-*: initial;",
    "  --color-transparent: transparent;",
    "  --color-current: currentColor;",
    ...Object.keys(defaultTheme.colors).map((role) => `  --color-${role}: var(--ui-${role});`),
    "}",
    "",
    "@theme {",
    ...entries("font", typo.fontFamily),
    ...fontSizes,
    ...entries("font-weight", typo.fontWeight),
    ...entries("tracking", typo.letterSpacing),
    `  --spacing: ${spacingUnit};`,
    "  --radius-*: initial;",
    ...entries("radius", radius),
    "  --shadow-*: initial;",
    ...entries("shadow", shadows),
    "  --breakpoint-*: initial;",
    ...entries("breakpoint", breakpoints),
    ...entries("z-index", zIndex),
    ...entries("transition-duration", motion.duration),
    ...entries("ease", motion.easing),
    "  --default-transition-duration: var(--transition-duration-fast);",
    "  --default-transition-timing-function: var(--ease-standard);",
    "}",
    "",
  ].join("\n")

  return writeIfChanged(path.join(root, "src/styles/tokens.css"), css)
}

/* -------------------------------------------------------------------------- */
/*  Components → registry                                                     */
/* -------------------------------------------------------------------------- */

type Discovered = {
  slug: string
  dir: string
  metaFile: string
  mainFile: string
  sourceFiles: string[]
  storyFile?: string
  docsFile?: string
  examples: { id: string; title: string; description?: string; file: string; importName: string }[]
}

const isAuxiliary = (name: string) =>
  /\.(meta|stories|test|spec)\.tsx?$/.test(name) || name === "index.ts"

function discoverComponents(): Discovered[] {
  if (!existsSync(uiDir)) return []
  return readdirSync(uiDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort()
    .flatMap((slug): Discovered[] => {
      const dir = path.join(uiDir, slug)
      const metaFile = path.join(dir, `${slug}.meta.tsx`)
      if (!existsSync(metaFile)) return [] // internal primitive, not shown in the showcase

      const mainFile = path.join(dir, `${slug}.tsx`)
      if (!existsSync(mainFile)) throw new Error(`${rel(dir)} has a meta file but no ${slug}.tsx`)

      const files = readdirSync(dir)
      const sourceFiles = files
        .filter((f) => /\.tsx?$/.test(f) && !isAuxiliary(f))
        .sort((a, b) => (a === `${slug}.tsx` ? -1 : b === `${slug}.tsx` ? 1 : a.localeCompare(b)))
        .map((f) => path.join(dir, f))

      const storyFile = files.find((f) => /\.stories\.tsx?$/.test(f))
      const docsFile = files.find((f) => f === `${slug}.docs.md`)

      const examplesDir = path.join(dir, "examples")
      const examples = existsSync(examplesDir)
        ? readdirSync(examplesDir)
            .filter((f) => f.endsWith(".tsx"))
            .sort()
            .map((f) => {
              const file = path.join(examplesDir, f)
              const id = path.basename(f, ".tsx").replace(/^\d+[-_]/, "")
              return {
                id,
                title: titleFromFile(f),
                description: leadingDocComment(readFileSync(file, "utf8")),
                file,
                importName: `${toPascal(slug)}${toPascal(id)}Example`,
              }
            })
        : []

      return [
        {
          slug,
          dir,
          metaFile,
          mainFile,
          sourceFiles,
          storyFile: storyFile && path.join(dir, storyFile),
          docsFile: docsFile && path.join(dir, docsFile),
          examples,
        },
      ]
    })
}

/** First `/** ... *\/` comment in a file, used as an example's description. */
function leadingDocComment(source: string) {
  const match = source.match(/\/\*\*([\s\S]*?)\*\//)
  if (!match?.[1]) return undefined
  return match[1]
    .split("\n")
    .map((l) => l.replace(/^\s*\* ?/, "").trim())
    .filter(Boolean)
    .join(" ")
}

/* ---------------------------- Prop extraction ----------------------------- */

function createProgram(files: string[]) {
  const configPath = path.join(root, "tsconfig.json")
  const config = ts.readConfigFile(configPath, ts.sys.readFile)
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root)
  return ts.createProgram(files, { ...parsed.options, noEmit: true, incremental: false })
}

function isLiteralUnion(type: ts.Type): type is ts.UnionType {
  return type.isUnion() && type.types.every((t) => t.isStringLiteral() || t.isNumberLiteral())
}

function isBoolean(type: ts.Type) {
  if (type.flags & ts.TypeFlags.Boolean) return true
  return (
    type.isUnion() && type.types.length > 0 && type.types.every((t) => !!(t.flags & ts.TypeFlags.BooleanLiteral))
  )
}

function propKind(type: ts.Type, checker: ts.TypeChecker, typeText: string): PropKind {
  if (/\bReact(Node|Element)\b/.test(typeText)) return "node"
  if (isBoolean(type)) return "boolean"
  if (type.isStringLiteral() || isLiteralUnion(type)) return "enum"
  if (type.flags & ts.TypeFlags.String) return "string"
  if (type.flags & ts.TypeFlags.Number) return "number"
  if (type.getCallSignatures().length > 0) return "function"
  if (checker.isArrayType(type) || checker.isTupleType(type)) return "array"
  if (type.flags & ts.TypeFlags.Object) return "object"
  return "unknown"
}

/** Literal members in the order they are written in source (TS interns them in its own order). */
function writtenLiteralOrder(node: ts.TypeNode | undefined, checker: ts.TypeChecker, depth = 0): string[] {
  if (!node || depth > 5) return []
  if (ts.isUnionTypeNode(node)) return node.types.flatMap((t) => writtenLiteralOrder(t, checker, depth + 1))
  if (ts.isLiteralTypeNode(node)) {
    const lit = node.literal
    return ts.isStringLiteral(lit) || ts.isNumericLiteral(lit) ? [lit.text] : []
  }
  if (ts.isParenthesizedTypeNode(node)) return writtenLiteralOrder(node.type, checker, depth + 1)
  if (ts.isTypeReferenceNode(node)) {
    let symbol = checker.getSymbolAtLocation(node.typeName)
    if (symbol && symbol.flags & ts.SymbolFlags.Alias) symbol = checker.getAliasedSymbol(symbol)
    const decl = symbol?.getDeclarations()?.find(ts.isTypeAliasDeclaration)
    return decl ? writtenLiteralOrder(decl.type, checker, depth + 1) : []
  }
  return []
}

function extractProps(program: ts.Program, file: string): PropGroup[] {
  const checker = program.getTypeChecker()
  const sourceFile = program.getSourceFile(file)
  if (!sourceFile) return []
  const groups: PropGroup[] = []

  const isOwnDeclaration = (d: ts.Declaration) => !d.getSourceFile().fileName.includes("node_modules")

  ts.forEachChild(sourceFile, (node) => {
    if (!ts.isTypeAliasDeclaration(node) && !ts.isInterfaceDeclaration(node)) return
    const name = node.name.text
    const exported = node.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)
    if (!exported || !name.endsWith("Props")) return

    const type = checker.getTypeAtLocation(node.name)
    const props: (PropDoc & { position: number })[] = []

    for (const symbol of checker.getPropertiesOfType(type)) {
      const declarations = symbol.getDeclarations() ?? []
      const own = declarations.find(isOwnDeclaration)
      if (!own) continue // inherited from DOM / React types
      const tags = symbol.getJsDocTags(checker)
      if (tags.some((t) => t.name === "internal")) continue

      const optional = (symbol.flags & ts.SymbolFlags.Optional) !== 0
      const full = checker.getTypeOfSymbolAtLocation(symbol, node)
      const resolved = optional ? checker.getNonNullableType(full) : full
      const written =
        ts.isPropertySignature(own) && own.type ? own.type.getText().replace(/\s+/g, " ") : undefined

      let typeText: string
      let options: string[] | undefined
      if (isBoolean(resolved)) typeText = "boolean"
      else if (resolved.isStringLiteral() || isLiteralUnion(resolved)) {
        const members = resolved.isUnion() ? resolved.types : [resolved]
        const order = writtenLiteralOrder(ts.isPropertySignature(own) ? own.type : undefined, checker)
        const rank = (value: string) => (order.includes(value) ? order.indexOf(value) : order.length)
        const literals = members
          .map((t) => ({
            value: t.isStringLiteral() ? t.value : String((t as ts.NumberLiteralType).value),
            text: checker.typeToString(t),
          }))
          .sort((a, b) => rank(a.value) - rank(b.value))
        options = literals.map((l) => l.value)
        typeText = literals.map((l) => l.text).join(" | ")
      } else typeText = written ?? checker.typeToString(resolved)

      const defaultTag = tags.find((t) => t.name === "default")
      const description = ts.displayPartsToString(symbol.getDocumentationComment(checker)).trim()

      props.push({
        name: symbol.name,
        type: typeText,
        kind: propKind(resolved, checker, typeText),
        required: !optional,
        ...(defaultTag?.text ? { defaultValue: ts.displayPartsToString(defaultTag.text).trim() } : {}),
        ...(description ? { description } : {}),
        ...(options ? { options } : {}),
        position: own.getSourceFile() === sourceFile ? own.pos : Number.MAX_SAFE_INTEGER,
      })
    }

    props.sort((a, b) => a.position - b.position)
    groups.push({ component: name.replace(/Props$/, ""), props: props.map(({ position: _, ...p }) => p) })
  })

  return groups
}

/* ------------------------------- Emitters --------------------------------- */

function importPath(file: string) {
  return "@/" + rel(file).replace(/^src\//, "").replace(/\.tsx?$/, "")
}

function generateRegistry() {
  const components = discoverComponents()
  const program = createProgram(components.flatMap((c) => c.sourceFiles))

  const imports: string[] = [
    'import { eraseMeta, type GeneratedComponent } from "@/lib/registry/types"',
    "",
  ]
  const entries: string[] = []

  for (const c of components) {
    const metaName = `${toCamel(c.slug)}Meta`
    imports.push(`import ${metaName} from "${importPath(c.metaFile)}"`)
    for (const ex of c.examples) imports.push(`import ${ex.importName} from "${importPath(ex.file)}"`)

    const exportName = toPascal(c.slug)
    const props = c.sourceFiles.flatMap((f) => extractProps(program, f))
    // The primary props type comes first; it drives the playground controls.
    props.sort((a, b) => (a.component === exportName ? -1 : b.component === exportName ? 1 : 0))

    const examples = c.examples.map((ex) =>
      [
        "      {",
        `        id: ${JSON.stringify(ex.id)},`,
        `        title: ${JSON.stringify(ex.title)},`,
        ex.description ? `        description: ${JSON.stringify(ex.description)},` : null,
        `        file: ${JSON.stringify(rel(ex.file))},`,
        `        Component: ${ex.importName},`,
        "      },",
      ]
        .filter(Boolean)
        .join("\n")
    )

    entries.push(
      [
        "  {",
        `    slug: ${JSON.stringify(c.slug)},`,
        `    meta: eraseMeta(${metaName}),`,
        `    exportName: ${JSON.stringify(exportName)},`,
        `    props: ${JSON.stringify(props)},`,
        `    sourceFiles: ${JSON.stringify(c.sourceFiles.map(rel))},`,
        c.docsFile ? `    docsFile: ${JSON.stringify(rel(c.docsFile))},` : null,
        c.storyFile ? `    storyFile: ${JSON.stringify(rel(c.storyFile))},` : null,
        `    examples: [${examples.length ? "\n" + examples.join("\n") + "\n    " : ""}],`,
        "  },",
      ]
        .filter(Boolean)
        .join("\n")
    )
  }

  const componentsTs = `${HEADER}${imports.join("\n")}\n\nexport const generatedComponents: GeneratedComponent[] = [\n${entries.join("\n")}\n]\n`

  const loadersTs = `${HEADER}import { eraseMeta, type AnyShowcaseMeta } from "@/lib/registry/types"

/** Lazy meta loaders: each component's playground code becomes its own chunk. */
export const metaLoaders: Record<string, () => Promise<AnyShowcaseMeta>> = {
${components
  .map((c) => `  ${JSON.stringify(c.slug)}: () => import("${importPath(c.metaFile)}").then((m) => eraseMeta(m.default)),`)
  .join("\n")}
}
`

  const a = writeIfChanged(path.join(generatedDir, "components.ts"), componentsTs)
  const b = writeIfChanged(path.join(generatedDir, "loaders.ts"), loadersTs)
  return { changed: a || b, count: components.length }
}

/* -------------------------------------------------------------------------- */
/*  Main                                                                      */
/* -------------------------------------------------------------------------- */

async function run() {
  const started = performance.now()
  const tokensChanged = await generateTokens()
  const registry = generateRegistry()
  const ms = Math.round(performance.now() - started)
  const changed = [tokensChanged && "tokens", registry.changed && "registry"].filter(Boolean)
  console.log(
    `[generate] ${registry.count} components · ${changed.length ? `updated ${changed.join(", ")}` : "up to date"} · ${ms}ms`
  )
}

await run()

if (process.argv.includes("--watch")) {
  let timer: ReturnType<typeof setTimeout> | undefined
  let running = false
  const schedule = () => {
    clearTimeout(timer)
    timer = setTimeout(async () => {
      if (running) return schedule()
      running = true
      try {
        await run()
      } catch (error) {
        console.error("[generate]", error instanceof Error ? error.message : error)
      } finally {
        running = false
      }
    }, 200)
  }
  for (const dir of [uiDir, tokensDir]) watch(dir, { recursive: true }, schedule)
  console.log("[generate] watching src/components/ui and src/tokens")
}
